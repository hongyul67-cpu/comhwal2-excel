REF = re.compile(r'(\$?)([A-Z]{1,3})(\$?)([0-9]+)(?![A-Za-z0-9_(])')


def shift(f, dr):
    out, i, q = "", 0, False
    while i < len(f):
        ch = f[i]
        if ch == '"':
            q = not q; out += ch; i += 1; continue
        if not q and (i == 0 or not re.match(r'[A-Za-z0-9_.$]', f[i - 1])):
            m = REF.match(f, i)
            if m:
                row = m[4] if m[3] else str(int(m[4]) + dr)
                out += m[1] + m[2] + m[3] + row
                i = m.end(); continue
        out += ch; i += 1
    return out


def table(ws, r, c, head, rows, fmts=None, hfill=BLUE):
    for j, h in enumerate(head):
        cell = astext(ws.cell(row=r, column=c + j, value=h))
        cell.font = Font(bold=True, color="FFFFFF"); cell.fill = PatternFill("solid", fgColor=hfill)
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True); cell.border = BORDER
    for i, row in enumerate(rows, 1):
        for j, v in enumerate(row):
            cell = ws.cell(row=r + i, column=c + j, value=v)
            astext(cell)
            cell.border = BORDER
            cell.alignment = Alignment(horizontal="center", vertical="center")
            if fmts and j < len(fmts) and fmts[j]:
                cell.number_format = fmts[j]
            elif isinstance(v, (dt.date,)):
                cell.number_format = "yyyy-mm-dd"


def cap(ws, r, c, text, span=6):
    ws.merge_cells(start_row=r, start_column=c, end_row=r, end_column=c + span - 1)
    x = astext(ws.cell(row=r, column=c, value=text))
    x.font = Font(bold=True, size=11, color=NAVY)


